import type { VerifiedPaystackEvent } from './paystack-webhooks.ts';
import { isPlanId } from './engine/plan-engine.ts';

/**
 * A user's commercial entitlement is a set of independently purchased items.
 * Checkout creates a pending record with a server-generated reference.
 * A verified provider event can only activate that exact stored record.
 */
export type SubscriptionItemType = 'base_plan' | 'engine_pass';
export type SubscriptionItemStatus =
  | 'pending'
  | 'trialing'
  | 'active'
  | 'grace'
  | 'cancelled'
  | 'expired'
  | 'legacy';

export interface SubscriptionItem {
  readonly id: string;
  readonly userId: string;
  readonly itemType: SubscriptionItemType;
  /** Plan code for base_plan; engine code for engine_pass. */
  readonly itemCode: string;
  readonly status: SubscriptionItemStatus;
  readonly provider: string | null;
  readonly checkoutReference: string | null;
  readonly providerCustomerId: string | null;
  readonly providerSubscriptionId: string | null;
  readonly startsAt: number | null;
  readonly endsAt: number | null;
  readonly cancelAtPeriodEnd: boolean;
  /** Provider event identity which created the entitlement; legacy rows are marked explicitly. */
  readonly source: string | null;
  /** Provider event time used to ignore stale status changes. */
  readonly lastProviderEventAt: number | null;
  readonly createdAt: number;
  readonly updatedAt: number;
}

export interface CreateSubscriptionItem {
  id: string;
  userId: string;
  itemType: SubscriptionItemType;
  itemCode: string;
  /** Generated by FORGE and persisted before requesting Paystack checkout. */
  checkoutReference: string;
  /** Expected full checkout amount in the provider's minor currency unit. */
  expectedAmountMinor: number;
  currency: string;
  startsAt?: number | null;
  endsAt?: number | null;
  cancelAtPeriodEnd?: boolean;
  now: number;
}

export interface ActivateSubscriptionItem {
  /** Existing pending subscription-item id created by FORGE before checkout. */
  id: string;
  providerCustomerId?: string | null;
  providerSubscriptionId?: string | null;
  startsAt?: number | null;
  endsAt?: number | null;
  cancelAtPeriodEnd?: boolean;
}

export type PaystackSubscriptionMutation =
  | { readonly kind: 'activate'; readonly item: ActivateSubscriptionItem }
  | { readonly kind: 'set_status'; readonly providerSubscriptionId: string; readonly status: 'active' | 'grace' | 'cancelled' | 'expired' }
  | { readonly kind: 'mark_not_renewing'; readonly providerSubscriptionId: string };

export interface ApplyPaystackEventResult {
  readonly status: 'processed' | 'duplicate';
}

export interface SubscriptionItemStore {
  /** Creates only a pending Paystack checkout item; callers cannot grant a paid entitlement. */
  create(input: CreateSubscriptionItem): Promise<SubscriptionItem>;
  findById(id: string): Promise<SubscriptionItem | null>;
  listPendingByCheckoutReference(reference: string): Promise<SubscriptionItem[]>;
  listByUser(userId: string): Promise<SubscriptionItem[]>;
  /** Records the verified event and all its mutations in one database transaction. */
  applyPaystackEvent(
    event: VerifiedPaystackEvent,
    mutations: readonly PaystackSubscriptionMutation[],
  ): Promise<ApplyPaystackEventResult>;
}

export function validateSubscriptionItemInput(input: CreateSubscriptionItem): void {
  if (!input.id || input.id.length > 128) throw new Error('subscription item id must be 1 to 128 characters');
  if (!input.userId || input.userId.length > 128) throw new Error('subscription item user id must be 1 to 128 characters');
  if (!input.itemCode || input.itemCode.length > 128) throw new Error('subscription item code must be 1 to 128 characters');
  if (!input.checkoutReference || input.checkoutReference.length > 256) throw new Error('checkout reference must be 1 to 256 characters');
  if (!Number.isSafeInteger(input.expectedAmountMinor) || input.expectedAmountMinor <= 0) throw new Error('expected checkout amount must be a positive safe integer');
  if (!/^[A-Z]{3}$/.test(input.currency)) throw new Error('checkout currency must be a three-letter uppercase code');
  if (input.itemType !== 'base_plan' && input.itemType !== 'engine_pass') throw new Error('invalid subscription item type');
  if (input.itemType === 'base_plan' && !isPlanId(input.itemCode)) throw new Error('unknown base plan code');
  if (input.startsAt != null && input.endsAt != null && input.endsAt <= input.startsAt) {
    throw new Error('subscription item end date must be after start date');
  }
}

export function validatePaystackChargeForCheckout(
  event: VerifiedPaystackEvent,
  expectedAmountMinor: number | null,
  expectedCurrency: string | null,
): void {
  if (event.eventType !== 'charge.success') throw new Error('only a successful Paystack charge can complete checkout');
  if (expectedAmountMinor === null || expectedCurrency === null) {
    throw new Error('checkout has no validated amount and currency quote');
  }
  const rawData = event.payload.data;
  if (rawData === null || typeof rawData !== 'object' || Array.isArray(rawData)) {
    throw new Error('Paystack charge event has no valid data object');
  }
  const data = rawData as Record<string, unknown>;
  const nestedTransaction = data.transaction;
  const payment = nestedTransaction !== null && typeof nestedTransaction === 'object' && !Array.isArray(nestedTransaction)
    ? nestedTransaction as Record<string, unknown>
    : data;
  if (payment.status !== 'success' || payment.amount !== expectedAmountMinor || payment.currency !== expectedCurrency) {
    throw new Error('Paystack charge does not match the stored checkout amount and currency');
  }
}

export function validatePaystackEventMutation(
  event: VerifiedPaystackEvent,
  mutation: PaystackSubscriptionMutation,
): void {
  if (mutation.kind === 'activate' && event.eventType !== 'charge.success') {
    throw new Error('only a signed charge.success event can activate a checkout');
  }
  if (mutation.kind === 'mark_not_renewing' && event.eventType !== 'subscription.not_renew') {
    throw new Error('only a subscription.not_renew event can mark a subscription as not renewing');
  }
  if (mutation.kind === 'set_status') {
    const rawData = event.payload.data;
    const data = rawData !== null && typeof rawData === 'object' && !Array.isArray(rawData)
      ? rawData as Record<string, unknown>
      : {};
    const rawTransaction = data.transaction;
    const transaction = rawTransaction !== null && typeof rawTransaction === 'object' && !Array.isArray(rawTransaction)
      ? rawTransaction as Record<string, unknown>
      : {};
    const successfulPayment = data.status === 'success' || data.paid === true || data.paid === 1 ||
      transaction.status === 'success';
    const validEvent =
      (mutation.status === 'active' &&
        (event.eventType === 'charge.success' || event.eventType === 'invoice.update') && successfulPayment) ||
      (mutation.status === 'grace' && event.eventType === 'invoice.payment_failed') ||
      (mutation.status === 'cancelled' && event.eventType === 'subscription.disable' && data.status !== 'complete') ||
      (mutation.status === 'expired' && event.eventType === 'subscription.disable' && data.status === 'complete');
    if (!validEvent) throw new Error('provider event type or payment status cannot apply this subscription status');
  }
}

export function validatePaystackMutation(mutation: PaystackSubscriptionMutation): void {
  if (mutation.kind === 'activate') {
    if (!mutation.item.id || mutation.item.id.length > 128) {
      throw new Error('subscription item id must be 1 to 128 characters');
    }
    return;
  }
  if (mutation.kind === 'set_status' || mutation.kind === 'mark_not_renewing') {
    if (!mutation.providerSubscriptionId || mutation.providerSubscriptionId.length > 256) {
      throw new Error('provider subscription id must be 1 to 256 characters');
    }
    return;
  }
  throw new Error('invalid Paystack subscription mutation');
}
